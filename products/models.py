NON_NEGATIVE = [MinValueValidator(Decimal("0"))]


class Unit(models.Model):
    """A unit of measure. Seeded by migration: ml, L, g, kg and common count
    units. Only count units can be added later (see products.units)."""

    class Dimension(models.TextChoices):
        VOLUME = "volume", "Volume"
        MASS = "mass", "Mass"
        COUNT = "count", "Count"

    code = models.SlugField(max_length=20, unique=True)
    name = models.CharField(max_length=30, help_text="Singular, e.g. litre, bottle.")
    plural = models.CharField(max_length=30, help_text="E.g. litres, bottles.")
    symbol = models.CharField(max_length=12, help_text="Short form shown next to numbers, e.g. L, ml, bottle.")
    dimension = models.CharField(max_length=10, choices=Dimension.choices)
    factor = models.DecimalField(
        max_digits=12, decimal_places=3, default=Decimal("1"),
        help_text="Size in the dimension's smallest unit (ml or g). Count units are always 1.",
    )
    is_active = models.BooleanField(default=True)

    class Meta:
        ordering = ["dimension", "factor", "name"]
        constraints = [
            models.CheckConstraint(condition=Q(factor__gt=0), name="unit_factor_gt_0"),
            models.CheckConstraint(condition=~Q(dimension="count") | Q(factor=1), name="unit_count_factor_is_1"),
        ]

    def __str__(self):
        return self.symbol if self.dimension != self.Dimension.COUNT else self.name

    @property
    def is_base(self) -> bool:
        return self.factor == 1


class Category(TimeStampedModel):
    name = models.CharField(max_length=80)
    is_active = models.BooleanField(default=True)

    class Meta:
        ordering = ["name"]
        verbose_name_plural = "categories"
        constraints = [
            models.UniqueConstraint(
                Lower("name"), name="category_name_unique_ci",
                violation_error_message="A category with this name already exists.",
            )
        ]

    def __str__(self):
        return self.name


class ProductQuerySet(models.QuerySet):
    def active(self):
        return self.filter(is_active=True)

    def low_stock(self):
        """Active, stock-tracked products at or below their alert threshold."""
        return self.filter(
            is_active=True,
            track_stock=True,
            low_stock_threshold__isnull=False,
            stock_qty__lte=F("low_stock_threshold"),
        )


class Product(TimeStampedModel):
    """Something you stock and sell, e.g. "Liquid hand soap".

    Stock is one pool counted in `stock_unit`. The ways it's sold (5 L
    container, 500 ml bottle, loose per litre…) are SellingOptions, each with
    its own price. Invoice lines keep their own copy of what was charged, so
    editing a product never changes old invoices. Products are archived
    (is_active=False), never deleted once used.
    """

    name = models.CharField(max_length=120)
    sku = models.CharField("SKU", max_length=40, unique=True, null=True, blank=True)
    category = models.ForeignKey(
        Category, on_delete=models.PROTECT, null=True, blank=True, related_name="products"
    )
    description = models.TextField(blank=True)
    photo = models.ImageField(upload_to=product_photo_path, blank=True, validators=[validate_image_upload])
    # Small WebP copy for lists, generated by products.images — never uploaded directly.
    thumbnail = models.ImageField(upload_to=product_thumb_path, blank=True, editable=False)

    # Stock is counted in `stock_unit`: ml for liquids, g for powders, or a
    # count unit (piece, bottle…) for things counted one by one. stock_qty is a
    # cached running total of inventory.StockMovement and is only ever changed
    # by inventory.services — never edited directly.
    stock_unit = models.ForeignKey(
        Unit, on_delete=models.PROTECT, related_name="+",
        help_text="What stock is counted in. Liquids: ml. Powders: g. Bars, bottles counted one by one: piece/bottle.",
    )
    track_stock = models.BooleanField(default=True)
    stock_qty = models.DecimalField(max_digits=14, decimal_places=3, default=Decimal("0"), editable=False)
    low_stock_threshold = models.DecimalField(
        max_digits=14, decimal_places=3, null=True, blank=True, validators=NON_NEGATIVE,
        help_text="Alert at or below this amount (in the stock unit). Leave blank for no alert.",
    )

    # Values from before the unit system (kept for reference, not used).
    legacy_unit = models.CharField(max_length=30, blank=True, editable=False)
    legacy_package_size = models.CharField(max_length=40, blank=True, editable=False)
    legacy_price = models.DecimalField(max_digits=12, decimal_places=2, null=True, blank=True, editable=False)
    legacy_cost_price = models.DecimalField(max_digits=12, decimal_places=2, null=True, blank=True, editable=False)

    is_active = models.BooleanField(default=True)

    objects = ProductQuerySet.as_manager()

    class Meta:
        ordering = ["name"]
        indexes = [
            models.Index(fields=["name"]),
            models.Index(fields=["category", "is_active"]),
        ]
        constraints = [
            models.CheckConstraint(
                condition=Q(low_stock_threshold__isnull=True) | Q(low_stock_threshold__gte=0),
                name="product_low_stock_threshold_gte_0",
            ),
        ]

    def __str__(self):
        return self.name

    def save(self, *args, **kwargs):
        if self.sku == "":
            self.sku = None  # keep the unique constraint happy for blank SKUs
        if self._state.adding:
            # New products start at zero; opening stock is recorded as a stock-in.
            self.stock_qty = Decimal("0")
        elif kwargs.get("update_fields") is None:
            # Never write stock_qty from a (possibly stale) in-memory copy.
            # Only inventory.services changes it, via an F() update.
            kwargs["update_fields"] = [
                f.name for f in self._meta.concrete_fields if not f.primary_key and f.name != "stock_qty"
            ]
        super().save(*args, **kwargs)

    @property
    def is_low_stock(self) -> bool:
        return (
            self.track_stock
            and self.low_stock_threshold is not None
            and self.stock_qty <= self.low_stock_threshold
        )

    # --- selling options & display helpers ------------------------------
    @property
    def default_option(self):
        options = getattr(self, "_prefetched_objects_cache", {}).get("options")
        if options is not None:
            active = [o for o in options if o.is_active]
            return next((o for o in active if o.is_default), active[0] if active else None)
        return (self.options.filter(is_active=True).order_by("-is_default", "sort_order", "pk").first())

    @property
    def active_options(self) -> list:
        options = getattr(self, "_prefetched_objects_cache", {}).get("options")
        if options is None:
            options = self.options.all()
        return [o for o in options if o.is_active]

    @property
    def options_summary(self) -> str:
        """'5 L container, loose per L' — how this product is sold."""
        return ", ".join(o.label for o in self.active_options)

    @property
    def default_price(self):
        option = self.default_option
        return option.price if option else None

    @property
    def stock_display(self) -> str:
        from .units import format_in_display_unit
        return format_in_display_unit(self.stock_qty, self.stock_unit)

    @property
    def threshold_display(self) -> str:
        from .units import format_in_display_unit
        if self.low_stock_threshold is None:
            return ""
        return format_in_display_unit(self.low_stock_threshold, self.stock_unit)


class SellingOption(TimeStampedModel):
    """One way a product is sold, with its own price.

    * PACKAGE: a fixed pack, e.g. "500 ml bottle" containing 500 ml, KES 140
      per bottle. Quantity on an invoice = number of packs; stock goes down by
      packs × content. Never pro-rated.
    * MEASURE: priced per unit of measure, e.g. KES 250 per L. Quantity can be
      entered in any unit of the same kind (1,500 ml = 1.5 L = KES 375).
    """

    class Method(models.TextChoices):
        PACKAGE = "package", "Fixed pack or item"
        MEASURE = "measure", "By measure (per L, per kg…)"

    product = models.ForeignKey(Product, on_delete=models.PROTECT, related_name="options")
    method = models.CharField(max_length=10, choices=Method.choices, default=Method.PACKAGE)
    label = models.CharField(max_length=60, help_text="As shown on invoices, e.g. “500 ml bottle”, “5 L container”, “loose, per litre”.")
    package_unit = models.ForeignKey(
        Unit, on_delete=models.PROTECT, null=True, blank=True, related_name="+",
        limit_choices_to={"dimension": "count"}, help_text="What one pack is called: bottle, container, carton…",
    )
    content_quantity = models.DecimalField(
        max_digits=14, decimal_places=3, null=True, blank=True,
        help_text="How much stock one pack holds, in the product's stock unit (e.g. 500 for a 500 ml bottle).",
    )
    price_unit = models.ForeignKey(
        Unit, on_delete=models.PROTECT, null=True, blank=True, related_name="+",
        help_text="For measured prices: the price is per this unit (L, kg…).",
    )
    price = models.DecimalField(max_digits=12, decimal_places=2, validators=NON_NEGATIVE)
    cost_price = models.DecimalField(max_digits=12, decimal_places=2, null=True, blank=True, validators=NON_NEGATIVE)
    is_default = models.BooleanField(default=False, help_text="Pre-selected when this product is added to an invoice.")
    is_active = models.BooleanField(default=True)
    sort_order = models.PositiveSmallIntegerField(default=0)

    class Meta:
        ordering = ["product", "-is_default", "sort_order", "pk"]
        constraints = [
            models.CheckConstraint(condition=Q(price__gte=0), name="selling_option_price_gte_0"),
            models.CheckConstraint(condition=Q(cost_price__isnull=True) | Q(cost_price__gte=0),
                                   name="selling_option_cost_gte_0"),
            models.CheckConstraint(
                condition=~Q(method="package") | (Q(package_unit__isnull=False) & Q(content_quantity__gt=0)),
                name="selling_option_package_complete",
            ),
            models.CheckConstraint(condition=~Q(method="measure") | Q(price_unit__isnull=False),
                                   name="selling_option_measure_has_unit"),
            models.UniqueConstraint(fields=["product"], condition=Q(is_default=True),
                                    name="selling_option_one_default_per_product"),
        ]

    def __str__(self):
        return f"{self.product.name}, {self.label}"

    def clean(self):
        from .units import IncompatibleUnits, check_compatible

        if self.method == self.Method.PACKAGE:
            if not self.package_unit_id or not self.content_quantity:
                raise ValidationError("A pack needs a name (bottle, container…) and how much it contains.")
        elif self.method == self.Method.MEASURE:
            if not self.price_unit_id:
                raise ValidationError("Choose the unit the price is per (L, kg…).")
            if self.product_id and self.product.stock_unit_id:
                try:
                    check_compatible(self.price_unit, self.product.stock_unit)
                except IncompatibleUnits as exc:
                    raise ValidationError(
                        {"price_unit": f"Must be compatible with the stock unit ({self.product.stock_unit}). {exc.messages[0]}"}
                    )

    @property
    def price_per_label(self) -> str:
        """'per bottle', 'per L'."""
        if self.method == self.Method.MEASURE and self.price_unit:
            return f"per {self.price_unit.symbol}"
        return f"per {self.package_unit.name}" if self.package_unit else ""

    @property
    def content_display(self) -> str:
        from .units import format_in_display_unit
        if self.method != self.Method.PACKAGE or self.content_quantity is None:
            return ""
        return format_in_display_unit(self.content_quantity, self.product.stock_unit)
